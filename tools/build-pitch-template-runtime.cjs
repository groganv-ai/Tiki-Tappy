// Buildless browser metadata and exact replay paths from the approved SVGs.
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..'),directory='assets/pitch-templates-v2';
const metadata=JSON.parse(fs.readFileSync(path.join(root,directory,'faw-pitch-dimensions.json'),'utf8'));
function attrs(tag){return Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map(m=>[m[1],m[2]]))}
function guidance(svg){
 const arrow=svg.match(/<g class="attack-direction"[^>]*>([\s\S]*?)<\/g>/)?.[1].match(/<path\b[^>]*>/)?.[0];
 const group=svg.match(/<g class="pitch-guidance"[^>]*>([\s\S]*?)<\/g>/)?.[1]||'';
 return {arrow:arrow?attrs(arrow).d:null,labels:[...group.matchAll(/<text\b([^>]*)>([^<]*)<\/text>/g)].map(m=>({x:Number(attrs(m[1]).x),y:Number(attrs(m[1]).y),text:m[2]}))};
}
const presets=metadata.presets.map(p=>{
 const svg=fs.readFileSync(path.join(root,directory,path.basename(p.rotations[0].image)),'utf8');
 const markings=svg.match(/<g fill="none" stroke="#edf5df"[^>]*>([\s\S]*?)<\/g>/)?.[1];
 const dots=svg.match(/<g fill="#edf5df">([\s\S]*?)<\/g>/)?.[1];
 if(!markings||!dots)throw Error('Unrecognized approved SVG: '+p.id);
 const numeric=(tags,fields)=>[...tags].map(m=>{const a=attrs(m[0]);return fields.map(f=>Number(a[f]||0))});
 return {...p,version:metadata.templateVersion,
  rotations:p.rotations.map(v=>({...v,image:directory+'/'+path.basename(v.image),oppositionImage:directory+'/'+path.basename(v.oppositionImage)})),
  drawing:{paths:[...markings.matchAll(/<path\b[^>]*>/g)].map(m=>attrs(m[0]).d),rects:numeric(markings.matchAll(/<rect\b[^>]*>/g),['x','y','width','height']),circles:numeric(markings.matchAll(/<circle\b[^>]*>/g),['cx','cy','r']),spots:numeric(dots.matchAll(/<circle\b[^>]*>/g),['cx','cy','r']),guidance:{our:guidance(svg),opposition:guidance(fs.readFileSync(path.join(root,directory,path.basename(p.rotations[0].oppositionImage)),'utf8'))}}
 };
});
fs.writeFileSync(path.join(root,'pitch-template-data.js'),'// Generated by tools/build-pitch-template-runtime.cjs from approved v2 assets.\nconst PITCH_TEMPLATES='+JSON.stringify(presets)+';\n');
console.log('Built six geometry snapshots and rotation/image mappings.');
